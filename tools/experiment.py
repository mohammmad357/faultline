"""Regenerate all measurements and the publication figure. Optional matplotlib."""
import csv
import io
import json
import os
from pathlib import Path
import platform
import random
import statistics
import subprocess
import sys
import time

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT/'python'))
from faultline import simulate


def main():
    out = ROOT/'results'
    out.mkdir(exist_ok=True)
    rng = random.Random(20261011)
    seeds = [rng.randint(1, 0xffffffff) for _ in range(60)]
    scenarios = [('ring',0,3,1), ('shortcuts',2,3,1), ('fast-recovery',2,3,6)]
    records=[]
    for name, shortcuts, beta, gamma in scenarios:
        for seed in seeds:
            rows=list(simulate(200,shortcuts,beta,gamma,seed))
            records.append(dict(scenario=name,seed=seed,final_R=rows[-1][-1],
                                peak_I=max(r[5] for r in rows),duration=rows[-1][1]))
    with (out/'scenarios.csv').open('w',newline='',encoding='utf-8') as handle:
        writer=csv.DictWriter(handle,fieldnames=list(records[0]));writer.writeheader();writer.writerows(records)
    binary=ROOT/'build'/('faultline.exe' if os.name=='nt' else 'faultline')
    commands={'Python':[sys.executable,str(ROOT/'python/faultline.py')], 'C':[str(binary)]}
    measurements=[]
    args=[600,2,4,1,314159]
    for name, command in commands.items():
        subprocess.run([*command,*map(str,args)],capture_output=True,check=True)
        for trial in range(7):
            start=time.perf_counter()
            result=subprocess.run([*command,*map(str,args)],capture_output=True,text=True,check=True)
            elapsed=(time.perf_counter()-start)*1000
            rows=list(csv.DictReader(io.StringIO(result.stdout)))
            measurements.append(dict(engine=name,trial=trial,elapsed_ms=elapsed,events=len(rows)-1))
    with (out/'benchmark.csv').open('w',newline='',encoding='utf-8') as handle:
        writer=csv.DictWriter(handle,fieldnames=list(measurements[0]));writer.writeheader();writer.writerows(measurements)
    environment={'python':sys.version.split()[0],'platform':platform.system(),
                 'architecture':platform.machine(),'compiler':subprocess.check_output(['gcc','--version'],text=True).splitlines()[0],
                 'compile_flags':'-std=c11 -O2 -Wall -Wextra -Wpedantic -Werror -lm',
                 'benchmark_args':args,'trials':7,'scenario_N':200,'seeds':60,
                 'seed_generator':'random.Random(20261011).randint(1, 4294967295)'}
    (out/'environment.json').write_text(json.dumps(environment,indent=2)+'\n',encoding='utf-8')
    lines=['# Measured results','', 'Generated by `python tools/experiment.py`. The CSV files retain every trial.',
           '', '## Network experiments','', 'Each scenario uses 200 nodes and the same 60 randomly sampled seeds. Shortcuts are attempts per node, not guaranteed edges. All runs include early extinction; results are not conditioned on large outbreaks.',
           '', '| Scenario | Mean final R / 200 | Mean peak I | Final R range |', '|---|---:|---:|---:|']
    for name,*_ in scenarios:
        group=[r for r in records if r['scenario']==name]
        lines.append(f"| {name} | {statistics.mean(r['final_R'] for r in group):.2f} | {statistics.mean(r['peak_I'] for r in group):.2f} | {min(r['final_R'] for r in group)}–{max(r['final_R'] for r in group)} |")
    medians={name:statistics.median(r['elapsed_ms'] for r in measurements if r['engine']==name) for name in commands}
    lines += ['', 'The topology comparison also changes realized graph density: it does not isolate a pure shortcut effect. The recovery comparison holds generation parameters fixed. Sixty seeds describe this experiment, not a universal threshold or causal estimate.',
              '', '## CLI performance','', '| Engine | Median milliseconds | Events |', '|---|---:|---:|']
    for name in commands:
        lines.append(f"| {name} | {medians[name]:.3f} | {measurements[0]['events']} |")
    lines += ['',f"Measured Python/C ratio: **{medians['Python']/medians['C']:.2f}×** on this machine.",
              '', 'Seven trials after one warm-up per engine. End-to-end wall time includes process startup, graph generation, simulation and CSV output captured in memory. The same arguments and events are used for both. C was compiled with O2; Python was CPython. Measurements are hardware- and workload-specific, with no CI performance threshold.',
              '', '![Measured trajectories and distributions](../assets/experiment.svg)',
              '', 'The lines show one seed (314159), not an average. The boxes show all 60 final sizes, including extinction; whiskers extend to extrema. Time is in arbitrary model units.']
    (out/'RESULTS.md').write_text('\n'.join(lines)+'\n',encoding='utf-8')
    import matplotlib
    matplotlib.use('Agg')
    import matplotlib.pyplot as plt
    plt.rcParams.update({'font.family':'DejaVu Sans','svg.fonttype':'none'})
    with plt.style.context('dark_background'):
        fig,axes=plt.subplots(1,2,figsize=(12,4.8),layout='constrained')
        fig.patch.set_facecolor('#0d1527')
        colors=['#53d9df','#fcad61','#b6a1ff']
        for (name,shortcuts,beta,gamma),color in zip(scenarios,colors):
            rows=list(simulate(200,shortcuts,beta,gamma,314159))
            axes[0].step([r[1] for r in rows],[r[5] for r in rows],where='post',label=name,color=color)
        axes[0].set(xlabel='Model time (arbitrary units)',ylabel='Infected nodes',title='One seed. Three network experiments.')
        axes[0].legend(frameon=False)
        data=[[r['final_R'] for r in records if r['scenario']==name] for name,*_ in scenarios]
        boxes=axes[1].boxplot(data,tick_labels=[s[0] for s in scenarios],whis=(0,100),patch_artist=True)
        for box,color in zip(boxes['boxes'],colors):box.set_facecolor(color);box.set_alpha(.6)
        axes[1].set(ylabel='Final recovered nodes / 200',title='60 seeds: outbreak size is a distribution',ylim=(-5,205))
        for ax in axes:
            ax.set_facecolor('#0d1527');ax.grid(alpha=.15);ax.spines[['top','right']].set_visible(False)
        fig.suptitle('FAULTLINE  /  Stochastic networks, reproducible events',fontsize=17,fontweight='bold')
        (ROOT/'assets').mkdir(exist_ok=True)
        fig.savefig(ROOT/'assets/experiment.svg',facecolor=fig.get_facecolor())
        fig.savefig(ROOT/'assets/experiment.png',dpi=140,facecolor=fig.get_facecolor())
    print('\n'.join(lines[:25]))


if __name__=='__main__':main()
